function hg = bartzCorrelation(pc, cstar, Dt, A, At, mu, cp, Pr, gamma, M, T0, Tw)

% Sutton book page 335

sigma = ( ...
    0.5*(Tw/T0)*(1 + (gamma - 1)/2*M.^2) + 0.5).^(-0.68) .* ...
    (1 + (gamma - 1)./2*M.^2).^(-0.12);

hg = 0.026 / Dt^0.2 * ...
     (mu^0.2 * cp / Pr^0.6) * ...
     (pc ./ cstar).^0.8 .* ...
     (At ./ A).^0.9 .* ...
     sigma;
end