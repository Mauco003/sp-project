function rel = ShapiroRelations(M, gamma, dA_A, dT0_T0, fric)
% SHAPIRORELATIONS
% General 1D compressible-flow differential relations (Shapiro form)
%
% Inputs:
%   M        - Mach number [-]
%   gamma    - specific heat ratio [-]
%   dA_A     - differential area change dA/A [-]
%   dT0_T0   - differential total-temperature change dT0/T0 [-]
%   fric     - friction / streamwise-force term [-]
%
% Output:
%   rel      - struct containing all differential relations
%
% Notes:
%   For isentropic nozzle flow: dT0_T0 = 0, fric = 0
%   For Rayleigh flow:          dA_A   = 0, fric = 0
%   For Fanno flow:             dA_A   = 0, dT0_T0 = 0

B = 1 + (gamma - 1)/2 * M^2;
den = 1 - M^2;

%% ------------------------------------------------------------------------
% d(M^2)/(M^2)
% -------------------------------------------------------------------------
rel.dM2_M2 = ...
    (-2 * B / den) * dA_A + ...
    ((1 + gamma*M^2) * B / den) * dT0_T0 + ...
    (gamma * M^2 * B / den) * fric;

%% ------------------------------------------------------------------------
% dV/V
% -------------------------------------------------------------------------
rel.dV_V = ...
    (-1 / den) * dA_A + ...
    (B / den) * dT0_T0 + ...
    (gamma * M^2 / (2*den)) * fric;

%% ------------------------------------------------------------------------
% da/a
% -------------------------------------------------------------------------
rel.da_a = ...
    ((gamma - 1) * M^2 / (2*den)) * dA_A + ...
    (((1 - gamma*M^2) * B) / den) * dT0_T0 + ...
    (gamma * (gamma - 1) * M^4 / (4*den)) * fric;

%% ------------------------------------------------------------------------
% dT/T
% -------------------------------------------------------------------------
rel.dT_T = ...
    (((gamma - 1) * M^2) / den) * dA_A + ...
    (((1 - gamma*M^2) * B) / den) * dT0_T0 + ...
    (gamma * (gamma - 1) * M^4 / (2*den)) * fric;

%% ------------------------------------------------------------------------
% d(rho)/rho
% -------------------------------------------------------------------------
rel.drho_rho = ...
    (M^2 / den) * dA_A + ...
    (-B / den) * dT0_T0 + ...
    (gamma * M^2 / (2*den)) * fric;

%% ------------------------------------------------------------------------
% dp/p
% -------------------------------------------------------------------------
rel.dp_p = ...
    (gamma * M^2 / den) * dA_A + ...
    (-gamma * M^2 * B / den) * dT0_T0 + ...
    (-gamma * M^2 * (1 + (gamma - 1)*M^2) / (2*den)) * fric;

%% ------------------------------------------------------------------------
% dp0/p0
% -------------------------------------------------------------------------
rel.dp0_p0 = ...
    0 * dA_A + ...
    (-gamma * M^2 / 2) * dT0_T0 + ...
    (-gamma * M^2 / 2) * fric;

%% ------------------------------------------------------------------------
% ds/cp
% -------------------------------------------------------------------------
rel.ds_cp = ...
    0 * dA_A + ...
    B * dT0_T0 + ...
    ((gamma - 1)/2 * M^2) * fric;

end